def _원문_제외(항목, 취득일):
    """⑥1호가목·3·4·5·6·8·9호를 노드와 따로 적은 독립 기준 — 노드(와 노드에 묻는 판정기)가 틀리면 여기서 잡힌다."""
    k, std, cap = 항목["종류"], 항목.get("시가표준액"), 항목["수도권"]
    if 항목.get("상속개시_5년내") or 항목.get("혼전분양권_배우자혼전주택"):
        return True
    if k == "주택":
        if 항목["정비구역"] or not std:
            return False
        return std <= (100_000_000 if cap or (취득일 is not None and 취득일 < "2025-01-02") else 200_000_000)
    if k == "부속토지":
        return bool(std) and std <= 100_000_000
    if k != "오피스텔":
        return False
    if std and std <= 100_000_000:
        return True
    if 항목.get("전용면적", 999) > 60 or 항목.get("취득당시가액", 10**12) > (600_000_000 if cap else 300_000_000):
        return False
    if 취득일 is not None and 취득일 > "2028-12-31":
        return False
    신축, 기축 = 항목.get("신축최초유상승계일"), 항목.get("유상승계취득일")
    if 신축:
        return "2024-01-10" <= 신축 <= "2027-12-31"
    if 기축:
        return "2024-01-10" <= 기축 <= "2027-12-31" and bool(항목.get("임대등록_60일내")) and not 항목.get("임대의무위반")
    return False


