def _match(item: dict, taxpayer: str, assets: set[str], stages: set[str], context: set[str]) -> bool:
    cond = item["조건"]
    if "taxpayer" in cond and taxpayer not in cond["taxpayer"]:
        return False
    if cond.get("assets") is not None and assets and not (assets & set(cond["assets"])):
        return False
    if "stages" in cond and not (stages & set(cond["stages"])):
        return False
    if "context" in cond and not (context & set(cond["context"])):
        return False
    return True


