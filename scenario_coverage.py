    """List every Korean real-estate tax item to cover for a situation (who buys, what, which stages), with citations and whether this connector computes it.

    상황(납세자 × 물건 × 단계)마다 답변에서 다뤄야 할 세목·중과·예외·함정을 근거 조문과 함께 돌려준다.
    한 세목만 묻는 질문이 아니라 '법인으로 사서 1년 안에 판다', '경매로 여러 채', '증여 후 양도'처럼
    여러 단계·여러 세목이 걸린 질문에서 빠뜨리는 세목이 없게 하려는 목록이다. 판정이 아니다.
    각 항목의 '범위'는 이 커넥터가 계산하는지(엔진·부분) 아니면 계산하지 않는지(범위밖)를 표시한다.
    외부 조회를 하지 않고 금액·개인정보 없이 조회한다.

    Args:
        taxpayer: "개인" | "법인" | "매매사업자"
        assets: 물건 목록 — "주택", "분양권·입주권", "상가·건물", "토지", "비사업용토지", "농지".
            비우면 물건 무관 항목과 모든 물건의 항목을 돌려준다.
        stages: 단계 목록 — "취득", "보유", "임대", "양도", "증여", "상속". 비우면 취득·보유·양도.
        context: 해당하는 상황 — "경매·공매", "단기매매", "반복매매", "대도시", "조정대상지역".

    Returns:
        조건(정규화된 입력), 검토_항목(단계 순서, 각 id·세목·쟁점·요지·근거·범위·함정·계산_판정_도구),
        범위밖_항목(id 목록), 함정_항목(id 목록), 선택지(입력값 목록), 참고.
    """
    taxpayer = (taxpayer or "개인").strip()
    if taxpayer not in TAXPAYERS:
        raise ValueError(f"taxpayer는 {', '.join(TAXPAYERS)} 중 하나여야 한다: {taxpayer!r}")
    a, s, c = _split(assets), _split(stages) or ["취득", "보유", "양도"], _split(context)
    _check("assets", a, ASSETS)
    _check("stages", s, STAGES)
    _check("context", c, CONTEXTS)

    chosen = [i for i in ITEMS if _match(i, taxpayer, set(a), set(s), set(c))]
    order = list(STAGES)

    def stage_rank(item):
        st = item["조건"].get("stages") or set(order)
        return min(order.index(x) for x in st if x in s) if (set(st) & set(s)) else len(order)

    chosen.sort(key=lambda i: (stage_rank(i), _IDS.index(i["id"])))
    return {
        "조건": {"taxpayer": taxpayer, "assets": a, "stages": s, "context": c},
        "검토_항목": [_public(i) for i in chosen],
        "범위밖_항목": [i["id"] for i in chosen if i["범위"] == "범위밖"],
        "함정_항목": [i["id"] for i in chosen if i["함정"]],
        "선택지": {"taxpayer": TAXPAYERS, "assets": ASSETS, "stages": STAGES, "context": CONTEXTS},
        "참고": NOTES,
    }
