_KEYS = {item["key"] for item in ITEMS}


def _public(item: dict) -> dict:
    out = {"항목": item["key"], "질문": item["질문"], "이유": item["이유"], "근거": item["근거"]}
    if item.get("when"):
        out["필요한_경우"] = item["when"]
    return out


def get_acquisition_tax_checklist(acquisition_type: str = "", known: list[str] | None = None) -> dict:
    """List the facts needed to calculate Korean acquisition tax (취득세), in plain language, with statutory citations.

    취득세를 계산하려면 사용자가 무엇을 알려줘야 하는지, 각 정보가 왜 필요한지, 근거 조문을
    취득 원인별로 돌려준다. 거래금액이나 개인정보 없이 조회할 수 있고 외부 조회를 하지 않는다.

    Args:
        acquisition_type: "매매" | "분양" | "증여" | "상속". 모르면 비워 둔다 — 그러면 공통 항목과
            취득 원인 선택지를 돌려준다.
        known: 사용자가 이미 알려준 항목 키 목록(예: ["price", "location"]). 결과의 "물어볼_항목"에서 빠지고
            "받은_항목"으로 옮겨진다.

    Returns:
        취득원인, 물어볼_항목(항목·질문·이유·근거·필요한_경우), 받은_항목, 알수없는_항목, 참고.
    """
    acquisition_type = (acquisition_type or "").strip()
    known_set = {k.strip() for k in (known or []) if isinstance(k, str) and k.strip()}
    unknown = sorted(known_set - _KEYS)

    if acquisition_type and acquisition_type not in TYPES:
        raise ValueError(f"acquisition_type은 {', '.join(TYPES)} 중 하나이거나 빈 값이어야 합니다: {acquisition_type!r}")

    if acquisition_type:
        known_set.add("acquisition_type")
        items = [i for i in ITEMS if i["types"] is None or acquisition_type in i["types"]]
    else:
        items = [i for i in ITEMS if i["types"] is None]

    result = {
        "취득원인": acquisition_type or "미정",
        "물어볼_항목": [_public(i) for i in items if i["key"] not in known_set],
        "받은_항목": [i["key"] for i in items if i["key"] in known_set],
        "알수없는_항목": unknown,
        "참고": NOTES,
    }
    if not acquisition_type:
        result["취득원인_선택지"] = TYPES
    return result
