def 감면_종합한도(연도: int, 감면신청목록: list[dict], **사실) -> dict:
    """§129 배제 → §133①② 한도 → §127⑦ 택일 안내. 감면신청목록: [{조문, 감면세액, 라벨}]. 사실: 직전4년_감면, 직전4년_수용감면,
    계약서가액상이, 미등기, 분할후_동일인_양도, 토지일부_분리적용"""
    from tax_nodes.engine import 실행
    f = {"감면신청목록": 감면신청목록}
    f.update({k: v for k, v in 사실.items() if v is not None})
    ctx = 실행(f, 연도, 기준일="%d1231" % 연도, 세목="양도세감면")
    배제 = ctx.값("감면배제", None)
    if 배제:
        ctx.점검("조세특례제한법-129-1", "조세특례제한법-129-2")
        return {"감면가능": False, "최종감면세액": 0, "판정": 배제 + " — 비과세·감면 전면 배제",
                "적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()}
    인정1 = ctx.값("한도①_인정", 0)
    인정2 = ctx.값("한도②_인정", 0)
    열거 = _LIMIT1 | _LIMIT2
    한도외 = sum(int(r.get("감면세액", 0)) for r in 감면신청목록 if _조문키(r) not in 열거)
    ctx.점검("조세특례제한법-129-1", "조세특례제한법-129-2", "조세특례제한법-127-7", "조세특례제한법-133-3")
    return {"감면가능": True, "최종감면세액": int(인정1 + 인정2 + 한도외),
            "바스켓별": {"§133①": {"인정": 인정1, "배제": ctx.값("한도①_배제", 0), "적용한도": ctx.값("한도①_적용한도", "")},
                     "§133②": {"인정": 인정2, "배제": ctx.값("한도②_배제", 0)}, "한도외": 한도외},
            "택일필요": bool(ctx.값("택일필요", False)), "분할양도_합산간주": bool(ctx.값("분할양도_합산간주", False)),
            "과세연도": 연도, "적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()}
