점검대상 = ("지방세법시행령-111", "지방세법-122")


def 재산세_건축물(시가표준액: int, 연도: int, 용도: str = "일반", **사실) -> dict:
    """건축물분 재산세를 조문 노드의 합성으로 계산한다 — §110① → §111①2호·②·③ → §112 → §122 → §151①6호."""
    from tax_nodes.engine import 실행

    입력 = {"물건유형": "건축물", "건축물_세액계산": True, "시가표준액": int(시가표준액), "건축물_용도": 용도}
    입력.update({k: v for k, v in 사실.items() if v is not None})
    ctx = 실행(입력, 연도, 세목="재산세")
    ctx.기준일 = ctx.값("과세기준일")

    과세표준 = ctx.값("과세표준")
    본세 = ctx.값("제1호세액")
    도시지역분 = ctx.값("제2호세액", 0)
    ctx.값("재산세액")
    ctx.점검(*점검대상)
    상한 = ctx.계산값.get("세부담상한_내역")
    징수_본세 = 상한["제1호"]["징수세액"] if 상한 else 본세
    징수_도시 = 상한["제2호"]["징수세액"] if 상한 else 도시지역분
    지방교육세 = ctx.값("지방교육세")

    return {
        "시가표준액": int(시가표준액),
        "공정시장가액비율": ctx.값("재산세_토지_공정시장가액비율"),
        "과세표준": 과세표준,
        "세율구분": ctx.값("건축물_세율구분"),
        "표준세율": ctx.값("건축물_표준세율"),
        "조례가감 적용여부": bool(ctx.계산값.get("조례가감_적용", False)),
        "적용세율": ctx.값("적용세율"),
        "재산세 본세(산출세액)": 본세,
        "도시지역분(산출세액)": 도시지역분,
        "세부담상한": 상한,
        "재산세 본세": 징수_본세,
        "도시지역분": 징수_도시,
        "지방교육세": 지방교육세,
        "총납부세액": 징수_본세 + 징수_도시 + 지방교육세,
        "과세연도": 연도,
        "과세기준일": ctx.기준일,
        "최초과세기준일": ctx.계산값.get("최초과세기준일"),
        "값 출처": ctx.상수근거,
        "적용 조문": ctx.적용조문(),
        "미적용 조문": ctx.미적용목록,
        "근거표": ctx.근거표(),
    }
