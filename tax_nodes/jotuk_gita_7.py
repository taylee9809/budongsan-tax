def _소급합(이력, 기준일, 년, 키="세액"):
    """기준일부터 소급하여 N년 이내 감면세액 합. 연도 항목은 'N년이 되는 날이 속하는 과세연도 이후'(영 §116의7④), 일자 항목은 날짜로 본다."""
    기준 = _d(기준일)
    if 기준 is None:
        return 0
    시작 = _add_years(기준, -년)
    합 = 0
    for e in 이력 or []:
        if e.get("일자"):
            ok = 시작 <= _d(e["일자"]) <= 기준
        else:
            ok = 시작.year <= int(e["연도"]) <= 기준.year
        if ok:
            합 += int(e.get(키, 0) or 0)
    return 합


def _순차적용(금액들, 총감면):
    """여러 추징사유 — 동시 발생이면 큰 세액, 순차 발생이면 감면세액 범위에서 먼저 발생한 순서(영 §116의7⑤)."""
    if not 금액들:
        return 0
    if len(금액들) == 1:
        return min(금액들[0][1], 총감면) if 총감면 is not None else 금액들[0][1]
    if len({str(일) for 일, _ in 금액들}) == 1:
        return max(a for _, a in 금액들)
    누계 = 0
    for 일, a in sorted(금액들, key=lambda t: str(t[0])):
        누계 += min(a, max(0, 총감면 - 누계))
    return 누계


