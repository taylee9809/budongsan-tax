def _기간율(연차, 전, 후, r1, r2):
    if 연차 is None:
        return None
    if 1 <= 연차 <= 전:
        return r1
    if 전 < 연차 <= 전 + 후:
        return r2
    return 0


def _사업분산출세액(ctx):
    v = ctx.사실값("감면대상_산출세액")
