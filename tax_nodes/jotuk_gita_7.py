def 노드(**kw):
    """엔진 노드 등록 + 산출이 하나인 노드가 값 자체로 dict를 돌려주면 그 산출 이름으로 감싼다.

    엔진은 dict 반환을 '산출이름→값' 묶음으로 읽는다. {"세액": …} 같은 값 dict를 그대로 돌려주면
    산출이 비어 버리므로, 키가 산출 이름과 다르면 {산출[0]: 값}으로 바꾼다.
    """
    산출 = tuple(kw.get("산출", ()))

    def deco(fn):
        def wrapped(ctx):
            r = fn(ctx)
            if isinstance(r, dict) and len(산출) == 1 and set(r) != {산출[0]}:
                r = {산출[0]: r}
            return r
        wrapped.__name__ = fn.__name__
        wrapped.__doc__ = fn.__doc__
        _엔진노드(**kw)(wrapped)
        return fn
    return deco

