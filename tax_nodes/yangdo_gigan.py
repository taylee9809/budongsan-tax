    if a.get("임차인") and a.get("임차인") == b.get("임차인") and not 인상:
        return True, "동일 임차인 갱신·연장, 임대료 등 미증가 — 하나의 임대로 합산(서면-2023-법규재산-3010·서면-2024-법규재산-0980)"
