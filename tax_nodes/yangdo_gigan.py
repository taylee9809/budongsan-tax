# ============================================================== 날짜·기간 도구
def _d(v):
    if v in (None, ""):
        return None
    if isinstance(v, date):
        return v
    s = str(v).strip().replace(".", "-").replace("/", "-")
    if len(s) == 8 and s.isdigit():
        return date(int(s[:4]), int(s[4:6]), int(s[6:8]))
    p = [x for x in s.split("-") if x]
    if len(p) == 2:
        return date(int(p[0]), int(p[1]), 1)
    return date(int(p[0]), int(p[1]), int(p[2]))


def _iso(d):
    return d.isoformat() if d else None


def _ymd(d):
    return d.strftime("%Y%m%d")


def _만료일(시작: date, 개월: int) -> date:
    """시작일을 산입하는 기간이 '개월'을 채우는 마지막 날 — 민법 §160②③."""
    t = 시작.month - 1 + 개월
    y, m = 시작.year + t // 12, t % 12 + 1
    last = calendar.monthrange(y, m)[1]
    if 시작.day > last:
        return date(y, m, last)
    return date(y, m, 시작.day) - _하루


def _경과개월(시작: date, 끝: date) -> int:
    """시작일·끝일을 모두 산입할 때 완성된 월수."""
    if not 시작 or not 끝 or 끝 < 시작:
        return 0
    k = (끝.year - 시작.year) * 12 + (끝.month - 시작.month) + 1
    while k > 0 and _만료일(시작, k) > 끝:
        k -= 1
    return k


def _정리(구간):
    xs = sorted((a, b) for a, b in 구간 if a and b and a <= b)
    out = []
    for a, b in xs:
        if out and a <= out[-1][1] + _하루:
            out[-1] = (out[-1][0], max(out[-1][1], b))
        else:
            out.append((a, b))
    return out


def _빼기(구간, 제외):
    out = []
    for a, b in 구간:
        segs = [(a, b)]
        for x, y in 제외:
            new = []
            for s, e in segs:
                if y < s or x > e:
                    new.append((s, e))
                    continue
                if s < x:
                    new.append((s, x - _하루))
                if e > y:
                    new.append((y + _하루, e))
            segs = new
        out += segs
    return out


def _자르기(구간, 허용):
    out = []
    for a, b in 구간:
        for x, y in 허용:
            s, e = max(a, x), min(b, y)
            if s <= e:
                out.append((s, e))
    return out


def _합산(구간) -> dict:
    g = _정리(구간)
    일수 = sum((b - a).days + 1 for a, b in g)
    if len(g) <= 1:
        개월 = _경과개월(*g[0]) if g else 0
    else:
        개월 = 잔여 = 0
        for a, b in g:
            k = _경과개월(a, b)
            개월 += k
            s = a if k == 0 else _만료일(a, k) + _하루
            잔여 += max(0, (b - s).days + 1)
        개월 += 잔여 // 30
    return {"구간": [[_iso(a), _iso(b)] for a, b in g], "일수": 일수, "개월": 개월, "연수": 개월 // 12}


