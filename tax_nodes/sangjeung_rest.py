def _기간만료(기준일: date, 개월: int) -> date:
    """민법 §157·§160 — 기준일 다음날을 기산일로 하여 개월 후 기산일 응당일의 전일."""
    from datetime import timedelta
    return _plus_months(기준일 + timedelta(days=1), 개월) - timedelta(days=1)


def _plus_months(d: date, 개월: int) -> date:
    y, m = d.year, d.month + 개월
    while m > 12:
        y, m = y + 1, m - 12
    return date(y, m, min(d.day, calendar.monthrange(y, m)[1]))


