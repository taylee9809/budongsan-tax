def _호번호(ctx, 이름: str, 허용, 조문: str):
    """호 입력을 정수로 읽는다. 없으면 None, 범위 밖이면 미적용 사유 문자열."""
    v = ctx.사실값(이름)
    if v is None:
        return None, "%s 해당 호(%s) 입력 없음" % (조문, 이름)
    try:
        n = int(v)
    except (TypeError, ValueError):
        return None, "%s에 %r호는 없다" % (조문, v)
    if n not in 허용:
        return None, "%s에 %s호는 없다" % (조문, v)
    return n, None


