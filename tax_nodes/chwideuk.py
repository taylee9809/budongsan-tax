def 세율합성(표준세율: float, 기준세율: float, *, 주택유상: bool, 중과13의2: float | None,
         p13_1: bool, p13_2: bool, p13_5: bool, 고급주택_겹침: bool) -> tuple[float, str]:
    """§11·§13·§13의2 가운데 적용 세율과 근거 조문을 고른다. 농특세 §5①6호가 표준세율을 2%로 치환해
    같은 구조로 재계산하므로 순수 함수로 둔다."""
    후보: list[tuple[float, str]] = [(표준세율, "§11 표준세율")]
    if p13_1 and p13_2:
        후보.append((표준세율 * 3, "§13⑥ — ①·② 동시: 표준세율×300%"))
    else:
        if p13_1:
            후보.append((표준세율 + 기준세율 * 2, "§13① — 표준세율 + 중과기준세율×200%"))
        if p13_2 and not 주택유상:
            # 주택(§11①8호)은 §13② 괄호로 §13의2①1호 세율이 된다 — 중과13의2 후보가 그것을 든다.
            후보.append((표준세율 * 3 - 기준세율 * 2, "§13② — 표준세율×300% − 중과기준세율×200%"))
    if p13_2 and p13_5 and not p13_1:
        if 주택유상:
            후보.append((표준세율 * 3 + 기준세율 * 2 + 기준세율 * 6, "§13⑦ 단서 — 주택: 표준세율×300% + 중과기준세율×200% + 중과기준세율×600%"))
        else:
            후보.append((표준세율 * 3 + 기준세율 * 2, "§13⑦ — ②·⑤ 동시: 표준세율×300% + 중과기준세율×200%"))
    elif p13_5:
        후보.append((표준세율 + 기준세율 * 4, "§13⑤ — 표준세율 + 중과기준세율×400%"))
    if 중과13의2 is not None:
        if 고급주택_겹침:
            후보.append((중과13의2 + 기준세율 * 4, "§13의2③ — §13의2 세율 + 중과기준세율×400% (고급주택 겹침)"))
        else:
            후보.append((중과13의2, "§13의2 — 법인·다주택·무상 중과세율"))
    세율, 근거 = max(후보, key=lambda t: t[0])
    if len(후보) > 1 and 근거.startswith("§11"):
        근거 = "§16⑤ — 둘 이상 세율 중 높은 세율: " + 근거
    elif len(후보) > 1:
        근거 = "§16⑤ 경합 중 최고: " + 근거
    return round(세율, 6), 근거


