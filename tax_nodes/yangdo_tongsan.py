# ============================================================== 합성 — 같은 과세기간 여러 건
def _건별(건: dict, 연도: int) -> dict:
    """'계산'(yangdo.양도세_부동산 인자)을 준 건은 한 건 계산으로 양도소득금액·세율구분을 얻는다."""
    if "계산" not in 건:
        return dict(건)
    from tax_nodes.yangdo import 양도세_부동산
    kw = dict(건["계산"])
    kw.setdefault("연도", 연도)
    kw.setdefault("양도일", 건.get("양도일") or "")
    r = 양도세_부동산(**kw)
    out = {k: v for k, v in 건.items() if k != "계산"}
    if r["양도차익"] <= 0:
        out.update(양도소득금액=r["양도차익"], 세율구분=건.get("세율구분", "기본"))
        return out
    if r.get("비과세") and not r.get("과세표준"):
        out.update(양도소득금액=0, 세율구분="기본", 비과세=r.get("비과세"))
        return out
    out["양도소득금액"] = r["공제후소득금액"]
    if "세율구분" not in 건:
        율, 누진 = r["적용세율(기본+중과)"], r["누진공제"]
        if kw.get("미등기"):
            구분 = "미등기"
        elif "단기세율" in str(r.get("채택", "")) and not 누진:
            구분 = "단기%d" % round(율 * 100)
        elif r.get("중과적용"):
            구분 = "중과%d" % round(r["중과가산세율"] * 100)
        elif kw.get("자산종류") == "비사업용토지":
            구분 = "비사업용"
        else:
            구분 = "기본"
        out["세율구분"] = 구분
    out["한건_양도소득세"] = r["양도소득세"]
    return out


