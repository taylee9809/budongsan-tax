def _목록(ctx):
    out = []
    for i, a in enumerate(ctx.사실값("양도자산목록") or []):
        a = dict(a)
        a.setdefault("자산", "자산%d" % (i + 1))
        a["호"] = int(a.get("호", 1) or 1)
        a.setdefault("세율구분", "기본")
        a["양도소득금액"] = float(a.get("양도소득금액") or 0)
        out.append(a)
    return out


def _묶음키(a):
    return (a["호"], a["세율구분"])


