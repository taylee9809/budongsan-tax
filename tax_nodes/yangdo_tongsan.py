@노드(id="소득세법시행령-167의2-1-1", 법령=_영, 조="167의2", 항="1", 호="1", 제목="양도차손 통산 1순위 — 같은 세율을 적용받는 자산의 양도소득금액", mst=_영MST,
    원문="1. 양도차손이 발생한 자산과 같은 세율을 적용받는 자산의 양도소득금액",
    산출=("통산_1호",),
    비고=("법 §102① 각 호(소득 구분) 안에서만 통산한다. 같은 세율의 자산이 둘 이상이면 양도소득금액 비율로 나누어 뺀다(원문 무규정 — 2호의 안분 방식을 따른 처리, 소득세법-102-2 와 같다). "
        "돌려주는 값 {자산별: {자산: 1호 공제 후 금액}, 남은차손: {(호, 세율구분): 금액}}."))
def 영제167조의2제1항제1호(ctx):
    목록 = _목록(ctx)
    if not any(a["양도소득금액"] < 0 for a in 목록):
        return 미적용("양도차손이 발생한 자산이 없다")
    후 = {a["자산"]: max(a["양도소득금액"], 0.0) for a in 목록}
    남은 = {}
    for 키 in sorted({_묶음키(a) for a in 목록}):
        묶음 = [a for a in 목록 if _묶음키(a) == 키]
        손 = -sum(a["양도소득금액"] for a in 묶음 if a["양도소득금액"] < 0)
        익 = sum(후[a["자산"]] for a in 묶음)
        if 손 <= 0:
            continue
        공제 = min(손, 익)
        if 익 > 0:
            for a in 묶음:
                후[a["자산"]] -= 공제 * 후[a["자산"]] / 익
        if 손 - 공제 > 0:
            남은["%d|%s" % 키] = 손 - 공제
    return {"통산_1호": {"자산별": 후, "남은차손": 남은}}


