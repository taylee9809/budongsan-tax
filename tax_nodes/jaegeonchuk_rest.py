    if 개시 is None:
        return 미적용("부과개시일 미제출")
    합 = 0
    내역 = []
    for r in 목록:
        양도, 취득 = _d(r.get("양도일")), _d(r.get("취득일"))
        세액 = _n(r.get("양도소득세액"))
        if not (양도 and 취득):
            내역.append({"양도일": r.get("양도일"), "인정": 0, "사유": "취득·양도일 미제출"})
