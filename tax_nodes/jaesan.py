def _구간(과세표준: int, 세율표: list[dict]) -> tuple[float, int]:
    """누진세율표에서 (세율, 누진공제)를 고른다.

    upto=None 구간을 맨 뒤로 정렬하는 것은 server._apply_brackets와 같다 —
    앞에 오면 첫 반복에서 매칭돼 모든 과세표준에 최고세율이 붙는 버그가 있었다.
    """
    세율, 공제 = 0.0, 0
    for b in sorted(세율표, key=lambda b: (b["upto"] is None, b["upto"] or 0)):
        세율, 공제 = b["rate"], b["deduction"]
        if b["upto"] is None or 과세표준 <= b["upto"]:
            break
    return 세율, 공제


