#: 산출물에 필요하지 않아 수요 기반 해석이 건드리지 않지만, "봤다"는 기록을
#: 남겨야 하는 조문들. 2026-08-30 사고 때 없던 것이 바로 이 줄이다.
점검대상 = ("지방세법-122", "지방세법-111의2-3", "지방세법-111의2-4")


def 재산세_주택(시가표준액: int, 연도: int, 직전연도_시가표준액: int = 0,
             일세대일주택: bool = False, **덮어쓰기) -> dict:
    """주택분 재산세를 조문 노드의 합성으로 계산한다.

    덮어쓰기로 공정시장가액비율·세율표·도시지역분세율·지방교육세율을 직접 줄 수 있다
    (호출자 지정으로 기록에 남는다). server.calc_property_tax와 같은 규약이다.
    """
    from tax_nodes.engine import 실행

    사실 = {"시가표준액": 시가표준액,
          "직전연도_시가표준액": 직전연도_시가표준액,
          "1세대1주택": (True if 일세대일주택 else None)}   # False면 영 §110의2 노드(jaesan_toji)가 판정한다
    사실.update({k: v for k, v in 덮어쓰기.items() if v is not None})

    ctx = 실행(사실, 연도, 세목="재산세")
    # 과세기준일부터 확정한다 — 일몰·시행일 검사의 기준이므로 다른 노드보다 먼저 온다.
    ctx.기준일 = ctx.값("과세기준일")

    재산세액 = ctx.값("재산세액")
    지방교육세 = ctx.값("지방교육세")
    ctx.점검(*점검대상)

    return {
        "시가표준액(공시가격)": 시가표준액,
        "공정시장가액비율": ctx.값("공정시장가액비율"),
        "과세표준": ctx.값("과세표준"),
        "과표상한 적용여부": ctx.값("과표상한_적용여부", False),
        "적용세율": ctx.값("적용세율"),
        "누진공제": ctx.값("누진공제"),
        "재산세 본세": ctx.값("제1호세액"),
        "도시지역분": ctx.값("제2호세액", 0),
        "지방교육세": 지방교육세,
        "총납부세액": 재산세액 + 지방교육세,
        "과세연도": 연도,
        "과세기준일": ctx.기준일,
        "값 출처": ctx.상수근거,
        "적용 조문": ctx.적용조문(),
        "미적용 조문": ctx.미적용목록,
        "근거표": ctx.근거표(),
    }
