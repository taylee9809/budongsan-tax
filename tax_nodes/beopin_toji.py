def _d(v):
    if not v:
        return None
    if isinstance(v, date):
        return v
    s = str(v).replace("-", "").replace(".", "")
    return date(int(s[:4]), int(s[4:6]), int(s[6:8]))


def _addy(d: date, n: int) -> date:
    try:
        return d.replace(year=d.year + n)
    except ValueError:
        return d.replace(year=d.year + n, day=28)


