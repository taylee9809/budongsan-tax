def _노드(**kw):
    """engine.노드 + 산출이 하나인 노드가 dict 값을 돌려줄 때 {산출: 값}으로 감싼다
    (엔진은 dict 반환을 '산출별 값 묶음'으로 읽는다)."""
    산출 = tuple(kw.get("산출", ()))

    def deco(fn):
        def w(ctx):
            r = fn(ctx)
            if isinstance(r, dict) and len(산출) == 1 and set(r) != {산출[0]}:
                r = {산출[0]: r}
            return r
        w.__name__ = fn.__name__
        w.__doc__ = fn.__doc__
        kw["mst"] = 판(kw["법령"], kw["id"], kw.get("mst", ""))      # 현행 본문과 대조된 노드만 현행 판 번호
        노드(**kw)(w)
        return fn
    return deco


