def _율(v) -> Fraction:
    """0.5 / 50 / '50%' 모두 받는다. 1 초과는 퍼센트로 본다."""
    if isinstance(v, str) and v.endswith("%"):
        return Fraction(v[:-1]) / 100
    f = Fraction(str(v))
    return f / 100 if f > 1 else f


