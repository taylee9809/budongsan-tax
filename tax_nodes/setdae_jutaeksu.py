def 동일세대_판정(관계: str, 세목구분: str = "양도세", **사실) -> dict:
    """사실: 동거, 생계동일, 나이, 혼인이력, 중위소득40_이상, 미성년, 법률상이혼_생계동일, 사실혼, 동거봉양_합가, 직계비속_나이"""
    from tax_nodes.engine import 실행
    f = {"관계": 관계, "세목구분": 세목구분}
    f.update({k: v for k, v in 사실.items() if v is not None})
    ctx = 실행(f, 2026, 세목=("취득세" if 세목구분 == "취득세" else "세대주택수"))
    동일 = bool(ctx.값("동일세대", False))
    if 세목구분 == "양도세":
        분리 = ctx.값("세대분리가능", None) if 동일 else True
        조건 = ctx.값("분리조건", None)
    else:
        # 취득세: 주민등록표 기준 — 배우자와 미혼 30세 미만 자녀 외에는 주민등록표를 분리하면 별도 세대(영 §28의3①).
        예외 = bool(ctx.값("취득세_별도세대", False))
        분리 = (not 동일) or 예외
        조건 = None
        if 동일 and 관계 == "배우자":
            분리 = False
        elif 동일 and 관계 == "직계비속" and 사실.get("나이") is not None and int(사실["나이"]) < 30 and not 사실.get("혼인이력", False):
            분리 = bool(사실.get("중위소득40_이상", False) and not 사실.get("미성년", False))
        elif 동일 and 관계 == "직계존속" and 사실.get("동거봉양_합가", False):
            분리 = 예외                                   # 65세·30세 요건을 못 채운 합가는 별도세대 예외 불가
        elif 동일:
            분리, 조건 = True, "세대별 주민등록표 분리"
    return {"동일세대": 동일, "분리가능": bool(분리), "분리조건": 조건, "값 출처": ctx.상수근거,
            "적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()}


