def _가산세_사실준비(f: dict) -> bool:
    """가산세 사실이 하나라도 있으면 True — 그때만 기한내신고 기본값(신고세액 유무)과 법정신고기한(§67①④·§68①)을 채운다.
    가산세 노드 모듈(gibon_jeolcha·sangjeung_gasanse)은 여기서 늦게 불러오고, 전역 세목설정 값을 되돌린다."""
    if not any(f.get(k) is not None for k in _가산세_사실키):
        return False
    import tax_nodes.engine as _E
    이전 = _E._현재세목
    try:
        import tax_nodes.gibon_jeolcha  # noqa: F401
        import tax_nodes.sangjeung_gasanse as _G
    finally:
        _E._현재세목 = 이전
    f.setdefault("기한내신고", f.get("신고세액") is not None)
    상속 = f.get("세목구분") == "상속"
    성립 = _G._d(f.get("납세의무성립일") or (f.get("상속개시일") if 상속 else f.get("증여일")))
    if f.get("법정신고기한") is None and 성립 is not None:
        f["법정신고기한"] = _G._iso(_G._개월후_말일(성립, (9 if f.get("외국주소") else 6) if 상속 else 3))
    if "기한내납부" not in f:
        if f.get("기한내납부세액") is not None and f.get("신고세액") is not None:
            f["기한내납부"] = int(f["기한내납부세액"]) >= int(f["신고세액"])
        else:
            f["기한내납부"] = bool(f["기한내신고"])
    return True


