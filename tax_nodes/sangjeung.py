def _ymd(v) -> str:
    """'2023.4.12'·'2023-04-12'·'20230412' → '2023-04-12' (비교용). 없으면 ''."""
    if v is None or v == "":
        return ""
    s = str(v).strip().replace(".", "-").replace("/", "-")
    if "-" not in s and len(s) >= 8:
        s = "%s-%s-%s" % (s[:4], s[4:6], s[6:8])
    y, m, d = (s.split("-") + ["1", "1"])[:3]
    return "%04d-%02d-%02d" % (int(y), int(m), int(d[:2]))


