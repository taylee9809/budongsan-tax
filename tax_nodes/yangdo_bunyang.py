    if 제외:
        return 미적용("§97의2② 적용 제외 — " + 제외)
    취득가액 = int(ctx.사실값("증여자_취득가액", 0) or 0)
    필요경비 = int(ctx.사실값("증여자_자본적지출", 0) or 0) + int(ctx.사실값("양도비", 0) or 0) + int(ctx.값("이월과세_증여세상당액", 0) or 0)
    차익 = int(ctx.사실값("양도가액", 0) or 0) - 취득가액 - 필요경비
    return {"이월과세_적용": True, "이월과세_취득가액": 취득가액, "이월과세_필요경비": 필요경비, "이월과세_양도차익": 차익}


