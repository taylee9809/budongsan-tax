def _norm(A):
    A = sorted((a, b) for a, b in A if a and b and a <= b)
    out = []
    for a, b in A:
        if out and a <= out[-1][1] + _하루:
            if b > out[-1][1]:
                out[-1] = (out[-1][0], b)
        else:
            out.append((a, b))
    return out


def _sub(A, B):
    A = _norm(A)
    for bs, be in _norm(B):
        nxt = []
        for a, b in A:
            if be < a or bs > b:
                nxt.append((a, b))
                continue
            if a < bs:
                nxt.append((a, bs - _하루))
            if be < b:
                nxt.append((be + _하루, b))
        A = nxt
    return A


def _cut(A, s, e):
    return _norm([(max(a, s), min(b, e)) for a, b in A if not (b < s or a > e)])


def _days(A):
    return sum((b - a).days + 1 for a, b in _norm(A))


def _ivs(A):
    return [[_iso(a), _iso(b) if b != _FAR else None] for a, b in _norm(A)]


