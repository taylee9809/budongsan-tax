세목설정("법인세")

_법, _영, _지 = "법인세법", "법인세법 시행령", "지방세법"
_법MST, _영MST, _지MST = "280349", "290843", "282559"

_주택류 = ("주택", "별장")
_권리류 = ("조합원입주권", "분양권")
_종류 = _주택류 + ("비사업용토지",) + _권리류 + ("그밖",)


def _자산(ctx) -> list[dict]:
    out = []
    for i, a in enumerate(ctx.사실값("양도자산") or []):
        종류 = a.get("종류", "그밖")
        if 종류 not in _종류:
            raise ValueError("양도자산[%d].종류는 %s 중 하나여야 합니다: %r" % (i, " | ".join(_종류), 종류))
        out.append(dict(a, 종류=종류, 라벨=a.get("라벨") or "%s %d" % (종류, i + 1)))
    return out


def _구간세액(과세표준: float, 세율표: list[dict]) -> int:
    if 과세표준 <= 0:
        return 0
    for b in sorted(세율표, key=lambda b: (b["upto"] is None, b["upto"] or 0)):
        if b["upto"] is None or 과세표준 <= b["upto"]:
            return max(int(과세표준 * b["rate"]) - b["deduction"], 0)
    return 0


def _표(ctx, 키: str, 이름: str) -> list[dict]:
    ctx.상수근거[이름] = tax_params.cite(키, ctx.연도)
    return tax_params.get_brackets(키, ctx.연도)


def _율(ctx, 키: str, 이름: str) -> dict:
    ctx.상수근거[이름] = tax_params.cite(키, ctx.연도)
    return tax_params.get_param(키, ctx.연도)


