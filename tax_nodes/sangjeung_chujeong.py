def _저가고가(ctx):
    """(유형, 시가, 대가, 차액) — 이익을 얻은 자 기준. 저가양수는 양수자, 고가양도는 양도자가 이익을 얻는다."""
    시가, 대가 = ctx.사실값("시가"), ctx.사실값("대가")
    if 시가 is None or 대가 is None:
        return None
    시가, 대가 = _n(시가), _n(대가)
    유형 = ctx.사실값("거래유형") or ("저가양수" if 대가 < 시가 else "고가양도")
    if 유형 not in ("저가양수", "고가양도"):
        raise ValueError("거래유형은 저가양수 | 고가양도 중 하나여야 합니다: %r" % 유형)
    차액 = 시가 - 대가 if 유형 == "저가양수" else 대가 - 시가
    return 유형, 시가, 대가, 차액


