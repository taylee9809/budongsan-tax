# 국세기본법 시행령 §27의4① 1일 이자율 — 개정 시행일 전 기간은 종전 율(부칙 2019.2.12. §9, 2022.2.15. §6)
_일이자율표 = (
    (date(1900, 1, 1), Fraction(3, 10000), "영 §27의4(2008.2.29.~) 1일 1만분의 3"),
    (date(2019, 2, 12), Fraction(25, 100000), "영 §27의4(2019.2.12.) 1일 10만분의 25"),
    (date(2022, 2, 15), Fraction(22, 100000), "영 §27의4①(2022.2.15.) 1일 10만분의 22"),
)
_월이자율 = Fraction(67, 10000)       # 영 §27의4②(2026.7.1. 시행) 월 1만분의 67


def _일이자율(d: date) -> Fraction:
    r = _일이자율표[0][1]
    for 시작, 율, _ in _일이자율표:
        if d >= 시작:
            r = 율
    return r


def _이자(금액: int, 시작: date, 끝: date):
    """금액 × (시작~끝 일수, 양끝 포함) × 1일 이자율 — 이자율 개정일로 구간을 나눈다. (Fraction 합계, 일수, 구간 목록)."""
    if 금액 <= 0 or 시작 is None or 끝 is None or 끝 < 시작:
        return Fraction(0), 0, []
    경계 = [s for s, _, _ in _일이자율표[1:] if 시작 < s <= 끝]
    점 = [시작] + 경계 + [끝 + timedelta(days=1)]
    합, 구간 = Fraction(0), []
    for a, b in zip(점, 점[1:]):
        일 = (b - a).days
        율 = _일이자율(a)
        합 += 금액 * 일 * 율
        구간.append({"시작": _iso(a), "끝": _iso(b - timedelta(days=1)), "일수": 일, "일이자율": float(율)})
    return 합, (끝 - 시작).days + 1, 구간


def _경과개월(시작: date, 납부일: date) -> int:
    """시작일(지정납부기한 다음 날)부터 납부일 전날까지 경과한 개월 수 — 민법 §157·§160(말일 없으면 그 달 말일 만료)."""
    끝 = 납부일 - timedelta(days=1)
    k = 0
    while True:
        y, m = divmod(시작.month - 1 + k + 1, 12)
        y += 시작.year
        m += 1
        if 시작.day > _말일(y, m):
            만료 = date(y, m, _말일(y, m))
        else:
            만료 = date(y, m, 시작.day) - timedelta(days=1)
        if 만료 > 끝:
            return k
        k += 1


