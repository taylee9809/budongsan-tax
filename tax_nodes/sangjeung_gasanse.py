def 상증_가산세(연도: int | None = None, 세목구분: str = "증여", 납세의무성립일=None, 산출세액=None, 납부세액=None, 신고세액=None,
             기한내신고=None, 기한내납부세액=None, 법정신고기한=None, 납부일=None, 납부고지일=None, 지정납부기한=None, 미납일수=None,
             부정행위: bool = False, 역외거래: bool = False, 과소신고사유=None, 납부지연_제외사유=None, 결정경정일=None,
             정당한사유=None, 감면유형=None, 신고일=None, 경정예지=None, 기준일: str = "", 추가사실: dict | None = None) -> dict:
    """상속세·증여세 가산세(무신고·과소신고·납부지연 + 사실이 있으면 §78) — 항목별 금액·내역·합계.

    납부세액 = 신고하여야 할(결정) 납부세액. 주지 않으면 상증 본세 노드(산출세액·할증·기납부세액공제·신고세액공제)로 계산한다.
    신고세액 = 기한 내 신고한 납부세액(None 이고 기한내신고도 None 이면 무신고).
    기한내납부세액을 주지 않으면 기한 내 신고·납부로 보고 신고세액을 납부한 것으로 본다.
    """
    f = dict(추가사실 or {})
    f["세목구분"] = 세목구분
    for k, v in (("납세의무성립일", 납세의무성립일), ("산출세액", 산출세액), ("납부세액", 납부세액), ("신고세액", 신고세액),
                 ("기한내신고", 기한내신고), ("기한내납부세액", 기한내납부세액), ("납부일", 납부일), ("납부고지일", 납부고지일),
                 ("지정납부기한", 지정납부기한), ("미납일수", 미납일수), ("과소신고사유", 과소신고사유), ("납부지연_제외사유", 납부지연_제외사유),
                 ("결정경정일", 결정경정일), ("정당한사유", 정당한사유), ("감면유형", 감면유형), ("신고일", 신고일), ("경정예지", 경정예지)):
        if v is not None:
            f[k] = v
    f.setdefault("부정행위", 부정행위)
    f.setdefault("역외거래", 역외거래)
    if "기한내신고" not in f:
        f["기한내신고"] = f.get("신고세액") is not None
    성립 = _d(f.get("납세의무성립일") or (f.get("상속개시일") if 세목구분 == "상속" else f.get("증여일")))
    if 연도 is None:
        연도 = 성립.year if 성립 else 2026
    # 법정신고기한(§48② 감면 노드가 사실로 읽는다)
    if 법정신고기한 is not None:
        f["법정신고기한"] = 법정신고기한
    elif "법정신고기한" not in f and 성립 is not None:
        f["법정신고기한"] = _iso(_개월후_말일(성립, (9 if f.get("외국주소") else 6) if 세목구분 == "상속" else 3))
    # §47의4③6호(gibon_jeolcha)가 읽는 기한내신고·기한내납부
    if "기한내납부" not in f:
        if f.get("기한내납부세액") is not None and f.get("신고세액") is not None:
            f["기한내납부"] = _n(f["기한내납부세액"]) >= _n(f["신고세액"])
        else:
            f["기한내납부"] = bool(f["기한내신고"])
    ctx = 실행(f, int(연도), 기준일=기준일, 세목="상증세")
    합계 = ctx.값("상증_가산세합계")
    return {"합계": 합계, "항목": ctx.값("상증_가산세내역"),
            "무신고가산세": ctx.값("상증가산_무신고가산세", None), "무신고_내역": ctx.값("상증가산_무신고_내역", None),
            "과소신고가산세": ctx.값("상증가산_과소신고가산세", None), "과소신고_내역": ctx.값("상증가산_과소신고_내역", None),
            "납부지연가산세": ctx.값("상증가산_납부지연가산세", None), "납부지연_내역": ctx.값("상증가산_납부지연_내역", None),
            "공익법인등_내역": ctx.값("상증가산_공익법인가산세내역", None),
            "법정신고기한": ctx.값("상증가산_법정신고기한", None), "부과제외": ctx.값("국기_가산세_부과제외", None),
            "값 출처": ctx.상수근거, "적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()}
