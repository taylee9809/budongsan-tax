def 중과세율_판정(양도주택: dict, 보유목록: list[dict], 양도일: str = "", 양도당시_조정대상지역: bool | None = None, **사실) -> dict:
    """주택 목록을 주면 법 §104⑦의 어느 호인지 → 중과 대상 주택인지 → (조정대상지역을 주면) 가산세율까지 조립한다.

    보유목록  양도일 현재 1세대가 가진 주택·조합원입주권·분양권 전부(양도주택 포함). 항목 키는 이 파일 머리말과 중과판정_주택수 참조.
              양도주택이 목록에 없으면(라벨로 대조) 맨 앞에 넣는다.
    사실      혼인일·혼인후_신규취득일(⑨항·§167의4⑤), 1주택간주_특례근거·154①요건충족(13호·15호) 등 노드가 읽는 사실.
              항목에 명의신탁유형·명의신탁_지위(·상대방_명의신탁약정_인지)가 있으면 부동산실명법 §4② 노드로 귀속을 정해 이 세대 것이 아닌 주택을 빼고,
              권리 항목에 지위_근거법률(·공급대상·지위내용)이 있으면 법 §88 10호 범위 노드로 분양권인지 정한다(2026-11-18 연결).
    계열 결정
      주택만 있는 세대   1호·12호를 뺀 주택 수가 3 이상 → 영 §167의3①(법 §104⑦3호, +30%p) / 2 → 영 §167의10①(1호, +20%p) / 그 밖 → 대상 아님.
                       3 이상인데 ⑨항 차감으로 3 미만이 되면 대상 아님(§167의10은 ⑨항을 준용하지 않고, 그 세대는 '2개 소유'도 아니다).
      입주권·분양권 포함  영 §167의4② 불산입 뒤 주택+권리 합이 3 이상 → §167의4③(4호, +30%p) / 주택 1 + 권리 1 → §167의11①(2호, +20%p).
                       권리가 불산입으로 모두 빠지면 주택만 있는 세대와 같이 본다.
    반환  중과대상(조정대상지역은 보지 않은 '대통령령으로 정하는 주택' 해당 여부), 적용호, 중과계열, 가산_주택수(2|3 — 세율 구분용), 제외사유, 판정(세부 결과),
          중과적용·중과가산세율·장기보유특별공제_배제(양도당시_조정대상지역을 준 경우에만 값이 있다).
    """
    from tax_nodes import yangdo_jungkwa
    from tax_nodes.setdae_jutaeksu import 중과판정_주택수, _명의신탁_정리, _분양권범위_정리
    양도 = 양도일 or 양도주택.get("양도일") or ""
    h = dict(양도주택)
    h.setdefault("라벨", "양도주택")
    if 양도:
        h.setdefault("양도일", 양도)
    목록 = [dict(it) for it in (보유목록 or [])]
    for i, it in enumerate(목록):
        if _라벨(it) == h["라벨"]:
            목록[i] = h = dict(it, **h)
            break
    else:
        목록.insert(0, h)
    # 부동산실명법 §4②(명의신탁 주택의 귀속)·법 §88 10호(분양권의 범위) — 세대의 것이 아닌 항목을 먼저 뺀다. 해당 키가 없는 목록은 그대로다(2026-11-18 연결).
    목록, 명의신탁제외 = _명의신탁_정리(목록)
    목록, 분양권아님 = _분양권범위_정리(목록)
    out = {"중과대상": False, "적용호": None, "중과계열": None, "가산_주택수": 0, "제외사유": [], "판정": None}
    if 명의신탁제외:
        out["명의신탁_제외"] = 명의신탁제외
    if 분양권아님:
        out["분양권_아님"] = 분양권아님
    if not any(it is h or _라벨(it) == h["라벨"] for it in 목록):
        out["제외사유"] = ["양도주택이 이 세대의 주택이 아니다 — " + "; ".join(why for _, why in 명의신탁제외 + 분양권아님)]
        out["비고"] = "명의신탁 귀속(부동산실명법 §4②)상 양도주택의 소유자가 이 세대가 아니다 — 귀속자 쪽에서 판정한다"
        out.update({"중과적용": None, "중과가산세율": None, "장기보유특별공제_배제": None})
        return out

    def 끝(**kw):
        out.update(kw)
        if 양도당시_조정대상지역 is None:
            out.update({"중과적용": None, "중과가산세율": None, "장기보유특별공제_배제": None,
                        "비고": "양도당시_조정대상지역 미입력 — 중과 대상 주택 해당 여부까지만 판정했다"})
        else:
            적용 = bool(out["중과대상"] and 양도당시_조정대상지역)
            가산, 근거 = 0.0, ""
            if 적용:
                import tax_judgment
                가산, 근거 = tax_judgment._heavy_surcharge(out["가산_주택수"], _d(양도))
            out.update({"중과적용": 적용, "중과가산세율": 가산, "장기보유특별공제_배제": 적용, "가산세율_근거": 근거})
            if out["중과대상"] and not 양도당시_조정대상지역:
                out["제외사유"] = out["제외사유"] + ["법 §104⑦ — 양도 당시 조정대상지역에 있는 주택이 아님"]
        return out

    if h.get("종류", "주택") in _권리:
        return 끝(제외사유=["법 §104⑦은 주택의 양도에 적용한다 — %s 양도" % h["종류"]])
    주택 = [it for it in 목록 if it.get("종류", "주택") not in _권리]
    권리있음 = len(주택) != len(목록)
    if 권리있음:
        전체수 = 중과판정_주택수(목록, 3)
        주택수 = 중과판정_주택수(주택, 3)["중과판정_주택수"]
        권리수 = 전체수["중과판정_주택수"] - 주택수
        if 권리수 > 0:
            합 = 주택수 + 권리수
            혼인 = _d(사실.get("혼인일"))
            if 혼인 and 합 >= 3 and _d(양도):
                # §167의4⑤ — 혼인 5년 이내 양도 시 배우자 보유분(②항 불산입 뒤) 차감
                ok, why = yangdo_jungkwa.혼인완충_적용(혼인, _d(양도), _d(사실.get("혼인후_신규취득일")))
                배우자 = sum(1 for it in 목록 if it.get("배우자_보유") and _라벨(it) not in set(전체수["불산입"]))
                if ok and 배우자 and not h.get("배우자_보유") and 합 - 배우자 < 3:
                    return 끝(중과계열=3, 적용호="법 §104⑦4호", 판정={"주택수": 합 - 배우자, "차감전": 합},
                             제외사유=["영 §167의4⑤ — %s, 배우자 보유 %d개를 빼면 %d개(3 미만)" % (why, 배우자, 합 - 배우자)])
            if 합 >= 3:
                r = yangdo_jungkwa.중과제외_판정(h, 3, 목록, 양도, **사실)
                return 끝(중과대상=not r["중과제외"], 적용호="법 §104⑦4호", 중과계열=3, 가산_주택수=3, 제외사유=list(r["사유"]),
                         판정=dict(r, 주택수=합, 불산입=전체수["불산입"]))
            if 주택수 == 1 and 권리수 == 1:
                if _라벨(h) in set(전체수["불산입"]):
                    return 끝(중과계열=2, 적용호="법 §104⑦2호", 판정={"주택수": 합, "불산입": 전체수["불산입"]},
                             제외사유=["영 §167의11①3호 — 수 계산에서 빠지는 주택(지방 3억 이하·§167의3①12호)"])
                r = yangdo_jungkwa.중과제외_판정(h, 2, 목록, 양도, **사실)
                return 끝(중과대상=not r["중과제외"], 적용호="법 §104⑦2호", 중과계열=2, 가산_주택수=2, 제외사유=list(r["사유"]),
                         판정=dict(r, 주택수=합, 불산입=전체수["불산입"]))
            return 끝(판정={"주택수": 합, "불산입": 전체수["불산입"]},
                     제외사유=["주택 %d + 입주권·분양권 %d — 법 §104⑦2호(1주택+1권리)·4호(합 3 이상) 어느 쪽도 아님" % (주택수, 권리수)])
    r3 = 중과대상_판정(h, 주택, 3, 양도, **사실)
    if r3["주택수"] >= 3 or r3.get("차감전_주택수", 0) >= 3:
        return 끝(중과대상=bool(r3["중과대상"]), 적용호="법 §104⑦3호", 중과계열=3, 가산_주택수=3, 제외사유=list(r3["제외사유"]), 판정=r3)
    if r3["주택수"] == 2:
        r2 = 중과대상_판정(h, 주택, 2, 양도, **사실)
        return 끝(중과대상=bool(r2["중과대상"]), 적용호="법 §104⑦1호", 중과계열=2, 가산_주택수=2, 제외사유=list(r2["제외사유"]), 판정=r2)
    return 끝(판정=r3, 제외사유=["1호·12호 주택을 빼면 %d주택 — 1세대 2주택·3주택 이상 어느 쪽도 아님" % r3["주택수"]])


def 양도주택_사실(ctx) -> dict:
    """양도세 계산 경로(세목 '양도세')의 사실에서 중과 판정용 양도주택 항목을 만든다 — '양도주택'(dict)에 없는 키는 상위 사실에서 채운다."""
    h = dict(ctx.사실값("양도주택") or {})
    for 키, 상위 in _양도주택_상위키:
        if 키 not in h:
            v = ctx.값(상위, None) if 상위 == "보유연수" else ctx.사실값(상위)
            if v is not None:
                h[키] = v
    if ctx.사실값("양도일"):
        h.setdefault("양도일", ctx.사실값("양도일"))
    return h
