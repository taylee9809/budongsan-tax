    r = ctx.값("중과대상_3주택" if 중과계열 == 3 else "중과대상_2주택")
    return dict(r, 중과계열=중과계열, **{"적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()})


