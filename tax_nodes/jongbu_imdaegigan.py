    if 공가간주:
        진행중 = True
    return {"임대기간_연": None if 월 is None else round(월 / 12.0, 4), "임대월수": 월, "임대의무기간_진행중": 진행중,
            "기산일": 기산["기산일"] if 기산 else None, "근거": 근거}
