def _이자_63(ctx, 사유연도, 대상연도=None):
    """영 §60⑧ — 납부세액 × (감면받은 과세연도 종료일 다음 날 ~ 사유 발생 과세연도 종료일) × 율(호출자 '이자율_일').

    감면내역 연도별로 계산해 합한다. 대상연도 집합이 주어지면 그 연도만.
    """
    율 = ctx.사실값("이자율_일")
    if 율 is None:
        return None
    합 = 0
    for r in ctx.사실값("감면내역") or []:
        y = int(r["과세연도"])
        if 대상연도 is not None and y not in 대상연도:
            continue
        일수 = (date(int(사유연도), 12, 31) - date(y, 12, 31)).days
        if 일수 > 0:
            합 += int(Decimal(int(r["감면세액"])) * 일수 * Decimal(str(율)))
    return 합


