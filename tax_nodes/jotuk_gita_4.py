def _소급감면세액(ctx, 사유일, 년):
    """'사유일부터 소급하여 N년 이내에 감면된 세액' — 사실 '감면내역'=[{과세연도, 감면세액}], 과세연도 종료일이 (사유일 − N년) 이후이고 사유일 이전인 연도의 합."""
