def _고용한도(ctx, 투자율):
    """감면한도 = 투자누계액 × 투자율 + 상시근로자 수 × 1천5백만원(청년 상시근로자·서비스업은 2천만원) — 1호 먼저 적용 후 2호."""
    투자 = _n(ctx, "투자누계액")
    if 투자 is None:
        return None
    일반 = float(_n(ctx, "상시근로자수", 0)) - float(_n(ctx, "청년등_상시근로자수", 0))
    if ctx.사실값("감면대상서비스업", False):
        고용 = float(_n(ctx, "상시근로자수", 0)) * 20_000_000
    else:
        고용 = 일반 * 15_000_000 + float(_n(ctx, "청년등_상시근로자수", 0)) * 20_000_000
    투자분 = int(int(투자) * 투자율)
    return {"투자분": 투자분, "고용분": int(고용), "한도": 투자분 + int(고용)}


def _한도적용(ctx, 감면세액, 투자율):
    h = _고용한도(ctx, 투자율)
    if h is None:
        return None
    기감면 = int(_n(ctx, "기감면세액누계", 0))
    잔여 = max(0, h["한도"] - 기감면)
    적용 = min(int(감면세액), 잔여)
    투자잔여 = max(0, h["투자분"] - 기감면)
    고용사용 = max(0, 적용 - 투자잔여)
    return dict(h, 기감면세액누계=기감면, 잔여한도=잔여, 감면세액=적용, 고용한도_적용분=고용사용)


