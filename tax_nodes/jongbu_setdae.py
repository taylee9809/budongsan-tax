def 일세대일주택자_간주(other_homes: list[dict], base_date: str = "", 연도: int | None = None) -> dict:
    """법 §8④ 간주 4유형 — tax_judgment.judge_jongbu_one_home_status와 같은 입력·같은 키('1세대1주택자_간주')."""
    from tax_nodes.engine import 실행
    bd = _d(base_date) if base_date else None
    y = 연도 or (bd.year if bd else 2026)
    항목별, ok_all, 조문, 미적용들 = [], True, [], []
    for it in other_homes:
        t = it.get("유형", "일반")
        label = it.get("라벨") or t
        사실 = {"과세기준일": base_date.replace("-", "") if base_date else None}
        if t == "부속토지":
            항목별.append({"항목": label, "간주인정": True, "사유": "다른 주택의 부속토지만 보유 — 간주 1유형 (법 §8④1호)"})
            조문.append("종합부동산세법 §8④1호")
            continue
        키 = {"일시적신규": ("일시적신규", "간주_일시적2주택"), "상속": ("상속주택", "간주_상속주택"),
             "지방저가": ("지방저가주택", "간주_지방저가주택")}.get(t)
        if not 키:
            항목별.append({"항목": label, "간주인정": False, "사유": "일반 주택 — 간주 유형 아님 → 1세대1주택자 탈락"})
            ok_all = False
            continue
        사실[키[0]] = it
        ctx = 실행(사실, y, 세목="종부세")
        if base_date:
            ctx.기준일 = base_date.replace("-", "")
        r = ctx.값(키[1])
