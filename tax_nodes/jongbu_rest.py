def _ctx(사실: dict, 연도: int):
    from tax_nodes.engine import 실행
    return 실행(dict(사실), 연도, 세목="종부세")


def 종부세_합계(연도: int, 주택_합산공시가격: int = 0, 토지_종합합산_공시가격: int = 0, 토지_별도합산_공시가격: int = 0, **사실) -> dict:
    """§5 — 주택분(jongbu.종부세_주택) + 토지분 종합합산·별도합산(jongbu_toji.종부세_토지)을 각각 계산해 합한다."""
    from tax_nodes.jongbu import 종부세_주택
    from tax_nodes.jongbu_toji import 종부세_토지
    def _세액(r):          # 공제 이하로 납세의무가 없으면 '종합부동산세' 키 없이 납부세액 0을 돌려준다
        return int(r.get("종합부동산세", r.get("납부세액", 0)) or 0)

    주택 = _세액(종부세_주택(주택_합산공시가격, 연도, **{k: v for k, v in 사실.items() if not k.startswith("토지")})) if 주택_합산공시가격 else 0
    종합 = _세액(종부세_토지(토지_종합합산_공시가격, 연도, 토지구분="종합합산")) if 토지_종합합산_공시가격 else 0
    별도 = _세액(종부세_토지(토지_별도합산_공시가격, 연도, 토지구분="별도합산")) if 토지_별도합산_공시가격 else 0
    ctx = _ctx({"주택분_종부세": 주택, "토지분_종합합산세액": 종합, "토지분_별도합산세액": 별도}, 연도)
    return {"종부세_합계": ctx.값("종부세_합계"), "내역": ctx.값("종부세_합계_내역"), "적용 조문": ctx.적용조문(), "근거표": ctx.근거표()}


def 종부세_판정(연도: int, **사실) -> dict:
    """§6·§7, 영 §2·§2의2·§10 — 감면 준용 공시가격·납세의무자·추징액."""
    ctx = _ctx(사실, 연도)
    out = {}
    for k in ("종부세_감면반영_공시가격", "종부세_감면반영_내역", "종부세_감면준용배제", "주택분_종부세_납세의무자", "종부세_지역주택조합등_해당",
              "종부세_추징세액", "종부세_추징이자", "종부세_추징내역"):
        v = ctx.값(k, None)
        if v is not None:
            out[k] = v
    out.update({"적용 조문": ctx.적용조문(), "미적용 조문": ctx.미적용목록, "근거표": ctx.근거표()})
    return out
